// Builds one self-contained HTML file that runs the real importer (parsers, layout, elbow routing) in any browser,
// phone included. Usage: node tools/preview/build.mjs [out.html]   (default: tools/preview/out/importer-preview.html)
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(process.argv[2] || `${here}/out/importer-preview.html`);

// the examples live in the import dialog; lift that object instead of copying it
const dialog = readFileSync(`${here}/../../excalidraw-app/components/InfraDialog.tsx`, "utf8");
const start = dialog.indexOf("const EXAMPLES");
const end = dialog.indexOf("\n};\n", start) + 3;
if (start < 0 || end < start) {
  throw new Error("Could not find EXAMPLES in InfraDialog.tsx");
}
writeFileSync(
  `${here}/examples.generated.ts`,
  `// generated by build.mjs from InfraDialog.tsx; do not edit\nexport ${dialog.slice(start, end).replace("Record<InfraFormat, string>", "Record<string, string>")}\n`,
);

const result = await build({
  entryPoints: [`${here}/entry.ts`],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "TrazoPreview",
  platform: "browser",
  target: "es2019",
  minify: true,
  logLevel: "warning",
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = readFileSync(`${here}/template.html`, "utf8").replace("/*__BUNDLE__*/", () => js);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, html);
console.log(`${out} (${(html.length / 1024).toFixed(0)} KB)`);
